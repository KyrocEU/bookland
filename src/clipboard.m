#import <AppKit/AppKit.h>

// Password managers mark secret or short-lived pasteboard contents with these
// standard pasteboard type names. Ignore the entire item before asking arboard
// for its text, so it never enters the in-memory history or the saved JSON.
int bookland_clipboard_is_sensitive(void) {
    @autoreleasepool {
        NSArray<NSPasteboardType> *types = NSPasteboard.generalPasteboard.types;
        if (!types) return 0;
        for (NSString *type in types) {
            if ([type isEqualToString:@"org.nspasteboard.ConcealedType"] ||
                [type isEqualToString:@"org.nspasteboard.TransientType"] ||
                [type isEqualToString:@"org.nspasteboard.AutoGeneratedType"] ||
                [type hasPrefix:@"com.agilebits.onepassword"]) {
                return 1;
            }
        }
        return 0;
    }
}

// Read only the bundle identifier of the frontmost app. Clipboard history can
// then skip selected apps without inspecting their pasteboard contents.
size_t bookland_frontmost_bundle_id(char *buffer, size_t capacity) {
    @autoreleasepool {
        NSString *identifier = NSWorkspace.sharedWorkspace.frontmostApplication.bundleIdentifier;
        if (!identifier || !buffer || capacity == 0) return 0;
        NSData *data = [identifier dataUsingEncoding:NSUTF8StringEncoding];
        if (!data || data.length >= capacity) return 0;
        memcpy(buffer, data.bytes, data.length);
        buffer[data.length] = 0;
        return data.length;
    }
}

long bookland_clipboard_change_count(void) {
    return NSPasteboard.generalPasteboard.changeCount;
}

// Finder writes file URLs, not path text. Return a bounded NUL-separated list
// so Rust can preserve the native file payload without reading unrelated data.
size_t bookland_clipboard_read_file_urls(char *buffer, size_t capacity) {
    @autoreleasepool {
        if (!buffer || capacity == 0) return 0;
        NSArray<NSURL *> *urls = [NSPasteboard.generalPasteboard
            readObjectsForClasses:@[[NSURL class]]
            options:@{NSPasteboardURLReadingFileURLsOnlyKey: @YES}];
        size_t used = 0;
        for (NSURL *url in urls) {
            if (!url.isFileURL || !url.path || used >= capacity || used > 65536) continue;
            NSData *data = [url.path dataUsingEncoding:NSUTF8StringEncoding];
            if (!data || data.length == 0 || data.length + 1 > capacity - used) return 0;
            memcpy(buffer + used, data.bytes, data.length);
            used += data.length;
            buffer[used++] = 0;
        }
        return used;
    }
}

int bookland_clipboard_write_file_urls(const char *buffer, size_t length) {
    @autoreleasepool {
        if (!buffer || length == 0 || length > 65536) return 0;
        NSMutableArray<NSURL *> *urls = [NSMutableArray array];
        size_t cursor = 0;
        while (cursor < length && urls.count < 32) {
            const char *end = memchr(buffer + cursor, 0, length - cursor);
            if (!end) return 0;
            size_t size = (size_t)(end - (buffer + cursor));
            if (size == 0 || size > 4096) return 0;
            NSString *path = [[NSString alloc] initWithBytes:buffer + cursor
                length:size encoding:NSUTF8StringEncoding];
            if (!path || ![NSFileManager.defaultManager fileExistsAtPath:path]) return 0;
            [urls addObject:[NSURL fileURLWithPath:path]];
            cursor += size + 1;
        }
        if (urls.count == 0 || cursor != length) return 0;
        NSPasteboard *pasteboard = NSPasteboard.generalPasteboard;
        [pasteboard clearContents];
        return [pasteboard writeObjects:urls] ? 1 : 0;
    }
}
